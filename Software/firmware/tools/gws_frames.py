#!/usr/bin/env python3
"""Cut the 0x197 / 0x3FD frames of one bus out of a SavvyCAN csv log into a
C++ include for the host tests (test/gws_f11_frames.inc).

  python3 tools/gws_frames.py egs-logs/F11_4log_r10md10m.csv > test/gws_f11_frames.inc

Only frames from 1 s before the first lever move to 1 s after the last
lever / P-button event are kept. The log stamp is the microsecond within the second and is unwrapped.
"""
import csv
import sys

BUS = "3"  # PT-CAN in the F11 4-bus logs


def main(path):
    rows = []
    last, wrap = -1, 0
    for r in csv.reader(open(path)):
        if len(r) < 10 or not r[0].isdigit():
            continue
        # The stamp is the microsecond within the second: unwrap it.
        t = int(r[0])
        if t < last - 500000:
            wrap += 1000000
        last = t
        if r[4] != BUS or r[1] not in ("00000197", "000003FD"):
            continue
        n = int(r[5])
        rows.append((t + wrap, int(r[1], 16), n, [int(x, 16) for x in r[6:6 + n]]))
    ev = [t for t, i, n, d in rows if i == 0x197 and (d[2] != 0x0F or d[3] != 0xC0)]
    t0, t1 = ev[0] - 1000000, ev[-1] + 1000000
    keep = [x for x in rows if t0 <= x[0] <= t1]
    base = keep[0][0]
    print("// GENERATED by tools/gws_frames.py from %s, bus %s. Do not edit." % (path.split("/")[-1], BUS))
    print("// {t_ms from the first frame, id, dlc, data}")
    for t, i, n, d in keep:
        print("{%d, 0x%03X, %d, {%s}}," % ((t - base) // 1000, i, n, ", ".join("0x%02X" % b for b in d)))


if __name__ == "__main__":
    main(sys.argv[1])
